export function parseBank(topics) {
  const out = [];
  for (const t of topics) {
    t.src.trim().split('\n').forEach((line, k) => {
      const m = line.trim().match(/^(\d+)\s*([?>_#~])\s*(.+?)\s+=\s+(.+)$/);
      if (!m) return;
      const abcd = m[4].includes(' | ');
      out.push({ id: `${t.id}-${k}`, topic: t.id, d: +m[1], type: m[2], q: m[3], abcd, a: m[4].split(abcd ? ' | ' : ' / ').map(s => s.trim()) });
    });
  }
  return out;
}
